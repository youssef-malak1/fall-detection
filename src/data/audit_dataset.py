"""Dataset audit for the UR Fall Detection Dataset (URFD).

Scans every downloaded video, reads its technical metadata with OpenCV, and writes:

  * ``data/processed/urfd_index.csv``  - one row per video
  * ``reports/data_audit.md``          - a human readable audit report

Run from the project root:

    python -m src.data.audit_dataset
"""

from __future__ import annotations

import re
from dataclasses import dataclass, asdict
from pathlib import Path

import cv2
import pandas as pd

PROJECT_ROOT = Path(__file__).resolve().parents[2]
RAW_DIR = PROJECT_ROOT / "data" / "raw" / "urfd"
PROCESSED_DIR = PROJECT_ROOT / "data" / "processed"
REPORTS_DIR = PROJECT_ROOT / "reports"

# fall-01-cam0.mp4 / adl-12-cam1.mp4
NAME_RE = re.compile(r"^(?P<class>fall|adl)-(?P<seq>\d{2})-cam(?P<camera>[01])\.mp4$")


@dataclass
class VideoInfo:
    file_name: str
    class_name: str
    sequence: str
    camera: int
    width: int
    height: int
    fps: float
    frame_count: int
    duration_s: float
    size_mb: float
    readable: bool


def probe(path: Path, raw_root: Path) -> VideoInfo:
    match = NAME_RE.match(path.name)
    if not match:
        raise ValueError(f"unexpected file name: {path.name}")

    cap = cv2.VideoCapture(str(path))
    readable = cap.isOpened()
    width = int(cap.get(cv2.CAP_PROP_FRAME_WIDTH))
    height = int(cap.get(cv2.CAP_PROP_FRAME_HEIGHT))
    fps = float(cap.get(cv2.CAP_PROP_FPS))
    frame_count = int(cap.get(cv2.CAP_PROP_FRAME_COUNT))
    cap.release()

    duration = frame_count / fps if fps > 0 else 0.0

    return VideoInfo(
        file_name=str(path.relative_to(raw_root)).replace("\\", "/"),
        class_name=match.group("class"),
        sequence=f"{match.group('class')}-{match.group('seq')}",
        camera=int(match.group("camera")),
        width=width,
        height=height,
        fps=round(fps, 3),
        frame_count=frame_count,
        duration_s=round(duration, 2),
        size_mb=round(path.stat().st_size / (1024 * 1024), 2),
        readable=readable,
    )


def build_dataframe(raw_root: Path) -> pd.DataFrame:
    videos = sorted(raw_root.rglob("*.mp4"))
    rows = []
    for path in videos:
        try:
            rows.append(asdict(probe(path, raw_root)))
        except Exception as exc:  # noqa: BLE001 - audit must never crash
            print(f"[warn] {path.name}: {exc}")
    return pd.DataFrame(rows)


def write_report(df: pd.DataFrame, out_path: Path) -> None:
    lines: list[str] = []
    add = lines.append

    add("# URFD data audit\n")
    add("Generated by `python -m src.data.audit_dataset`.\n")

    if df.empty:
        add("**No videos found.** Run `scripts/download_urfd.ps1` first.")
        out_path.write_text("\n".join(lines), encoding="utf-8")
        return

    total_h = df["duration_s"].sum() / 3600
    unique_events = df.groupby(["class_name", "sequence"]).ngroups
    multi_view = df.groupby("sequence")["camera"].nunique()
    add("## Summary\n")
    add(f"- Video files: **{len(df)}**")
    add(f"- **Unique events: {unique_events}** "
        f"({df[df['class_name'] == 'fall']['sequence'].nunique()} falls, "
        f"{df[df['class_name'] == 'adl']['sequence'].nunique()} ADL)")
    add(f"- Events with more than one camera view: **{int((multi_view > 1).sum())}**")
    add(f"- Total size: **{df['size_mb'].sum():.1f} MB**")
    add(f"- Total duration: **{df['duration_s'].sum() / 60:.1f} min** ({total_h:.2f} h)")
    add(f"- Unreadable files: **{int((~df['readable']).sum())}**")
    add(f"- Per class (files): {df['class_name'].value_counts().to_dict()}")
    add(f"- Per camera (files): {df['camera'].value_counts().to_dict()}\n")

    add("## Critical note on splitting\n")
    add("`fall-XX-cam0` and `fall-XX-cam1` are **the same physical event** recorded from "
        "two viewpoints. They must never end up on opposite sides of a train/test split — "
        "that is leakage. All splitting must be done at the **event** level "
        f"({unique_events} events), not at the file level ({len(df)} files).\n")

    add("## Technical metadata\n")
    add("| resolution | videos |")
    add("|---|---|")
    for res, count in df.groupby(df["width"].astype(str) + "x" + df["height"].astype(str)).size().items():
        add(f"| {res} | {count} |")
    add("")
    add("| field | min | median | max |")
    add("|---|---|---|---|")
    for col in ["fps", "frame_count", "duration_s", "size_mb"]:
        add(
            f"| {col} | {df[col].min():.2f} | {df[col].median():.2f} | {df[col].max():.2f} |"
        )
    add("")

    add("## Duration by class (seconds)\n")
    add("| class | n | mean | min | max | total |")
    add("|---|---|---|---|---|---|")
    for cls, group in df.groupby("class_name"):
        add(
            f"| {cls} | {len(group)} | {group['duration_s'].mean():.1f} | "
            f"{group['duration_s'].min():.1f} | {group['duration_s'].max():.1f} | "
            f"{group['duration_s'].sum():.1f} |"
        )
    add("")

    # frames per class -> the real class imbalance the model will see
    add("## Frame-level imbalance\n")
    add("| class | frames | share |")
    add("|---|---|---|")
    total_frames = df["frame_count"].sum()
    for cls, group in df.groupby("class_name"):
        frames = group["frame_count"].sum()
        add(f"| {cls} | {frames} | {100 * frames / total_frames:.1f}% |")
    add("")

    missing_cam1 = df[df["class_name"] == "adl"]["camera"].unique()
    if 1 not in missing_cam1:
        add("> Note: ADL sequences exist for camera 0 only — this matches the dataset "
            "description (cam1 was not recorded for ADLs).\n")

    add("## Files\n")
    add("| file | class | camera | res | fps | frames | duration (s) | size (MB) |")
    add("|---|---|---|---|---|---|---|---|")
    for row in df.sort_values(["class_name", "sequence", "camera"]).itertuples():
        add(
            f"| {row.file_name} | {row.class_name} | {row.camera} | "
            f"{row.width}x{row.height} | {row.fps} | {row.frame_count} | "
            f"{row.duration_s} | {row.size_mb} |"
        )

    out_path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> None:
    if not RAW_DIR.exists():
        raise SystemExit(f"No dataset at {RAW_DIR}. Run scripts/download_urfd.ps1 first.")

    PROCESSED_DIR.mkdir(parents=True, exist_ok=True)
    REPORTS_DIR.mkdir(parents=True, exist_ok=True)

    df = build_dataframe(RAW_DIR)
    csv_path = PROCESSED_DIR / "urfd_index.csv"
    df.to_csv(csv_path, index=False)

    report_path = REPORTS_DIR / "data_audit.md"
    write_report(df, report_path)

    print(f"videos      : {len(df)}")
    print(f"size (MB)   : {df['size_mb'].sum():.1f}")
    print(f"duration    : {df['duration_s'].sum() / 60:.1f} min")
    print(f"unreadable  : {int((~df['readable']).sum())}")
    print(f"wrote       : {csv_path}")
    print(f"wrote       : {report_path}")


if __name__ == "__main__":
    main()
